def new_wb():
    wb = Workbook()
    wb.properties.creator = "generate_test_data"
    wb.properties.created = FIXED_TS
    wb.properties.modified = FIXED_TS
    return wb

def write_staff():
    wb = new_wb()
    ws = wb.active
    ws.title = "Сотрудники"
    # порядок колонок намеренно не канонический
    ws.append(["Должность", "Код (Таб.No)", "Текущее состояние", "Наименование"])
    for fio, state, pos, code in STAFF:
        ws.append([pos, code, state, fio])
    wb.save(os.path.join(HERE, "staff_1c.xlsx"))

def write_cloud():
    wb = new_wb()
    ws = wb.active
    ws.title = "Реестр заказов"
    # намеренно: лишняя колонка «Менеджер» и перемешанный порядок колонок
    order = ["Заказ", "Менеджер", "Бренд", "Логист", "Статус",
             "Дата подтверждения", "Cut-off", "Дата получения УЛ",
             "Страна отправления", "Способ доставки",
             "Документы получены", "Комментарий", "Поставщик"]
    ws.append(order)
    for n, row in enumerate(CLOUD_ROWS):
        rec = dict(zip(CLOUD_HEADERS, row))
        rec["Менеджер"] = ["Белов А.А.", "Кира Е.С."][n % 2]  # лишняя колонка
        ws.append([rec[h] for h in order])
    wb.save(os.path.join(HERE, "cloud_registry.xlsx"))

